#!/usr/bin/env python3
"""Generate the browser and Apps Script catalog from the transfer JSON."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "NOMINATIONS_SOURCE.json"
REVIEW = ROOT / "data" / "catalog-review.json"
PUBLIC_OUT = ROOT / "public" / "data.js"
GAS_OUT = ROOT / "apps-script" / "Catalog.gs"
VERSION = "mpl-ballin-dor-2026-draft-1"


def js(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def main() -> None:
    PUBLIC_OUT.parent.mkdir(parents=True, exist_ok=True)
    GAS_OUT.parent.mkdir(parents=True, exist_ok=True)
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    review = json.loads(REVIEW.read_text(encoding="utf-8"))
    nomination_total = sum(len(item["nomines"]) for item in source["categories"])
    if len(source["categories"]) != 11 or nomination_total != 68:
        raise ValueError("Le transfert attendu comporte 11 catégories et 68 nominations.")
    categories = []
    for category in source["categories"]:
        categories.append(
            {
                "id": category["id"],
                "title": category["titre"],
                "nominees": [
                    {"id": f'{category["id"]}-N{index:02d}', "name": name}
                    for index, name in enumerate(category["nomines"], start=1)
                ],
            }
        )

    public_catalog = {
        "title": source["evenement"],
        "eyebrow": "Le vote des supporters",
        "catalogVersion": VERSION,
        "closingDate": "2026-12-01",
        "closesAt": "2026-12-01T23:59:59.000Z",
        "categories": categories,
        "pending": review["pending"],
    }
    PUBLIC_OUT.write_text(
        "// Generated by scripts/generate_catalog.py from data/NOMINATIONS_SOURCE.json.\n"
        f"export const ballot = {js(public_catalog)};\n",
        encoding="utf-8",
    )

    gas_catalog = {
        "version": VERSION,
        "categories": categories,
        "pending": review["pending"],
    }
    GAS_OUT.write_text(
        "// Generated by scripts/generate_catalog.py. Keep the browser and server catalogs in sync.\n"
        f"const CATALOG = {js(gas_catalog)};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
